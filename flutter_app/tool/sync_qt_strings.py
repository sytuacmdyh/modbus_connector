"""Extract the existing Qt Chinese dictionary without importing PySide6."""

import ast
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
source = ast.parse((root / "src/modbus_connector/i18n.py").read_text())
translations = {}
for node in source.body:
    if (
        isinstance(node, ast.AnnAssign)
        and isinstance(node.target, ast.Name)
        and node.target.id == "ZH_CN"
    ):
        translations.update(ast.literal_eval(node.value))
    elif isinstance(node, ast.Expr) and isinstance(node.value, ast.Call):
        call = node.value
        if (
            isinstance(call.func, ast.Attribute)
            and isinstance(call.func.value, ast.Name)
            and call.func.value.id == "ZH_CN"
            and call.func.attr == "update"
        ):
            translations.update(ast.literal_eval(call.args[0]))
text = "// Generated by tool/sync_qt_strings.py from i18n.py; no Qt runtime.\n"
text += "const qtChinese = <String, String>{\n"
for key, value in translations.items():

    def dart(value: str) -> str:
        return json.dumps(value, ensure_ascii=False).replace("$", "\\$")

    text += f"  {dart(key)}: {dart(value)},\n"
text += "};\n"
(root / "flutter_app/lib/src/qt_translations.dart").write_text(text)
